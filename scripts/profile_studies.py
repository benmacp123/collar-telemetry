"""Profile each committed study and write data/PROFILE.md.

Run with ``make profile``. Reads only files in data/raw/.
"""

import statistics
from collections import defaultdict
from pathlib import Path

from telemetry.geo import haversine_m
from telemetry.movebank import read_deployments, read_fixes

RAW = Path(__file__).resolve().parent.parent / "data" / "raw"
OUTPUT = RAW.parent / "PROFILE.md"

STUDIES = [
    (
        "Black-backed jackal, Etosha",
        "Black-backed jackal, Etosha National Park, Namibia",
    ),
    ("African elephant, Kruger", "ThermochronTracking Elephants Kruger 2007"),
]

# A gap is an interval longer than this many times the deployment's median.
GAP_FACTOR = 3


def profile_deployment(deployment, fixes):
    """Summary statistics for one deployment's fixes."""
    file_order = [fix.timestamp for fix in fixes]
    out_of_order = sum(
        later < earlier for earlier, later in zip(file_order, file_order[1:])
    )
    ordered = sorted(fixes, key=lambda fix: fix.timestamp)
    intervals = [
        (b.timestamp - a.timestamp).total_seconds() / 60
        for a, b in zip(ordered, ordered[1:])
    ]
    positive = [minutes for minutes in intervals if minutes > 0]
    median = statistics.median(positive) if positive else float("nan")
    speeds = [
        haversine_m(a.lat, a.lon, b.lat, b.lon) / (minutes * 60)
        for a, b, minutes in zip(ordered, ordered[1:], intervals)
        if minutes > 0
    ]
    last = ordered[-1].timestamp if ordered else None
    silent_days = (
        (deployment.deploy_off - last).total_seconds() / 86400
        if deployment.deploy_off and last
        else None
    )
    return {
        "deployment": deployment.deployment_id,
        "end type": deployment.end_type or "-",
        "fixes": len(fixes),
        "first": ordered[0].timestamp.date() if ordered else "-",
        "last": last.date() if last else "-",
        "median interval (min)": round(median),
        "gaps": sum(minutes > GAP_FACTOR * median for minutes in intervals),
        "longest gap (days)": round(max(intervals, default=0) / 1440, 1),
        "duplicate times": intervals.count(0),
        "out of order": out_of_order,
        "max speed (m/s)": round(max(speeds, default=0), 1),
        "last fix to deploy-off (days)": (
            "-" if silent_days is None else round(silent_days, 1)
        ),
    }


def markdown_table(rows):
    """Render a list of dicts with identical keys as a Markdown table."""
    header = list(rows[0])
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(row[key]) for key in header) + " |" for row in rows]
    return "\n".join(lines)


def main():
    """Profile every study and write the report."""
    sections = [
        "# Data profile",
        "",
        "Generated by `scripts/profile_studies.py` (`make profile`); do not edit.",
        f"A gap is an interval over {GAP_FACTOR}x the deployment's median interval.",
        "Max speed is the fastest implied speed between consecutive fixes, for",
        "screening only; it is not an outlier threshold.",
    ]
    for title, stem in STUDIES:
        deployments = read_deployments(RAW / f"{stem}-reference-data.csv")
        fixes, report = read_fixes(RAW / f"{stem}.csv", deployments)
        by_deployment = defaultdict(list)
        for fix in fixes:
            by_deployment[fix.deployment_id].append(fix)
        rows = [
            profile_deployment(d, by_deployment[d.deployment_id]) for d in deployments
        ]
        sections += [
            "",
            f"## {title}",
            "",
            f"{report.rows} event rows, {len(fixes)} fixes kept, "
            f"{len(deployments)} deployments. Dropped: {report.not_visible} "
            f"flagged as outliers, {report.no_location} without a location, "
            f"{report.unmatched} outside any deployment.",
            "",
            markdown_table(rows),
        ]
    OUTPUT.write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
